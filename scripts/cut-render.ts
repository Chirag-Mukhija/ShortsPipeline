// Renders a video's Cut plan (edit/cut.json): checks it, fills each segment's cues from the narration (or uses the plan's own on a music-only video), renders every segment as its own cached clip (only changed segments re-render), joins them with the soundtrack, makes a check sheet per segment, and runs the motion check.
// Usage: pnpm cut:render <videoId> [--final] [--only seg-a,seg-b] [--concurrency 4]
import { createHash, type Hash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, linkSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { checkCut, CutSchema, resolveCut, type ResolvedSegment } from "../packages/schema/src/cut";
import { cutContext } from "./lib/cut-kit";
import { gainToLufs, renderBed } from "./lib/music";

const FPS = 30;
const root = path.resolve(new URL("..", import.meta.url).pathname);
const pkg = path.join(root, "packages/video");
const videosRoot = process.env.STUDIO_VIDEOS_DIR ? path.resolve(process.env.STUDIO_VIDEOS_DIR) : path.join(root, "videos");

const args = process.argv.slice(2);
const id = args[0];
if (!id || id.startsWith("--")) {
  console.error("Usage: pnpm cut:render <videoId> [--final] [--only seg-a,seg-b] [--concurrency 4]");
  process.exit(2);
}
const opt = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const quality = args.includes("--final") ? "final" : "preview";
const forced = new Set((opt("only") ?? "").split(",").filter(Boolean));
const concurrency = opt("concurrency") ?? "4";

const videoDir = path.join(videosRoot, id);
const editDir = path.join(videoDir, "edit");
const planFile = path.join(editDir, "cut.json");
if (!existsSync(planFile)) throw new Error(`No edit/cut.json for ${id} yet.`);
const run = (cmd: string, argv: string[], cwd = pkg) => execFileSync(cmd, argv, { cwd, stdio: ["ignore", "pipe", "inherit"] }).toString();
const remotion = (argv: string[]) => run(path.join(pkg, "node_modules/.bin/remotion"), argv);

// 1. The plan must pass the checker before anything renders.
const raw = JSON.parse(readFileSync(planFile, "utf8"));
const report = checkCut(raw, cutContext(planFile));
for (const issue of report.issues) console.log(`  ${issue.level.toUpperCase().padEnd(6)} ${(issue.segment ?? "").padEnd(10)} ${issue.rule.padEnd(9)} ${issue.message}`);
if (!report.ok) {
  console.error(`cut.json has ${report.red} red issue(s); fix them first (pnpm cut:check ${path.relative(root, planFile)}).`);
  process.exit(1);
}
const cut = CutSchema.parse(raw);

// 2. Cues from the narration's word timings.
const narrationJson = path.join(videoDir, "record/narration.json");
const words = existsSync(narrationJson) ? (JSON.parse(readFileSync(narrationJson, "utf8")).words as { text: string; start: number; end: number }[]) : [];
const plan = resolveCut(cut, words, FPS);
const narrationWav = path.join(videoDir, "record/narration.wav");
if (cut.audio === "voice" && !existsSync(narrationWav)) throw new Error("There's no record/narration.wav. Export the voice-over first, or set audio: music on a music-only video.");
const facecam = path.join(videoDir, "record/facecam.mp4");
if (cut.faceCam && !existsSync(facecam)) throw new Error("The plan uses face cam but record/facecam.mp4 doesn't exist (export it on the Record page).");

// 3. The generated entry: the renderer plus this video's own scene files.
const sceneFiles = [...new Set(plan.segments.flatMap((s) => (s.visual?.kind === "scene" ? [s.visual.file] : [])))];
const rel = (to: string) => path.relative(editDir, to).split(path.sep).join("/");
writeFileSync(path.join(editDir, ".cut-plan.json"), JSON.stringify(plan));
writeFileSync(
  path.join(editDir, ".cut-entry.tsx"),
  `// Generated by scripts/cut-render.ts from cut.json; do not edit.
import { Composition, registerRoot } from "remotion";
import { CutVideo } from "${rel(path.join(pkg, "src/cut"))}";
import plan from "./.cut-plan.json";
${sceneFiles.map((f, i) => `import Scene${i} from "./${f.replace(/\.tsx?$/, "")}";`).join("\n")}
const scenes = { ${sceneFiles.map((f, i) => `${JSON.stringify(f)}: Scene${i}`).join(", ")} };
const Cut = () => <CutVideo plan={plan as never} scenes={scenes as never} ${cut.faceCam ? `face={{ src: "facecam.mp4" }}` : ""} />;
registerRoot(() => <Composition id="cut" component={Cut} durationInFrames={${plan.frames}} fps={${FPS}} width={1920} height={1080} />);
`,
);

// This video's scenes are typechecked before anything renders, so a broken scene fails in seconds with its line number.
const tsconfig = path.join(editDir, "tsconfig.json");
if (!existsSync(tsconfig)) {
  const up = rel(pkg);
  writeFileSync(tsconfig, JSON.stringify({ extends: `${up}/tsconfig.json`, compilerOptions: { paths: { "@library/*": [`./${up}/src/library/*`], "@kit/*": [`./${up}/src/kit/*`], "*": [`./${up}/node_modules/@types/*`, `./${up}/node_modules/*`] } }, include: ["scenes"] }, null, 2));
}
if (sceneFiles.length) {
  try {
    execFileSync(path.join(pkg, "node_modules/.bin/tsc"), ["-p", tsconfig, "--noEmit"], { cwd: editDir, stdio: "pipe" });
  } catch (error) {
    const lines = String((error as { stdout?: Buffer }).stdout ?? "").split("\n").filter((l) => /^scenes\/cut\/.*error/.test(l));
    if (lines.length) {
      console.error(lines.slice(0, 20).join("\n"));
      process.exit(1);
    }
  }
}

// 4. Cache keys: a segment re-renders only when its own JSON (cues included), its visual's code, its media, the style, the renderer or (for a transition in) the segment before it changes.
const hashTree = (dir: string, h: Hash) => {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith(".")) continue;
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) hashTree(p, h);
    else h.update(name).update(readFileSync(p));
  }
};
const engine = createHash("sha1");
hashTree(path.join(pkg, "src/cut"), engine);
hashTree(path.join(pkg, "src/library/core"), engine);
for (const f of ["contract.ts", "motion.tsx", "styles.ts"]) engine.update(readFileSync(path.join(pkg, "src/kit", f)));
const engineDigest = engine.digest("hex");
const stamp = (file: string) => (existsSync(file) ? `${statSync(file).size}:${statSync(file).mtimeMs}` : "missing");
const visualKey = (seg: ResolvedSegment, h: Hash) => {
  if (seg.visual?.kind === "template") h.update(readFileSync(path.join(pkg, "src/kit/templates", `${seg.visual.template}.tsx`)));
  if (seg.visual?.kind === "scene") {
    const file = path.join(editDir, seg.visual.file);
    h.update(readFileSync(file));
    // Shared helpers beside the scene (anything there that isn't itself a segment's scene).
    for (const name of readdirSync(path.dirname(file)).sort()) {
      const p = path.join(path.dirname(file), name);
      if (!sceneFiles.includes(path.relative(editDir, p).split(path.sep).join("/")) && statSync(p).isFile()) h.update(name).update(readFileSync(p));
    }
  }
  for (const m of seg.media) if (m.src) h.update(stamp(path.join(videoDir, m.src.startsWith("media/") ? m.src : `media/${m.src}`)));
  if (seg.layout !== "full" && cut.faceCam) h.update(stamp(facecam));
};
const keyOf = (i: number) => {
  const seg = plan.segments[i]!;
  const h = createHash("sha1").update(engineDigest).update(quality).update(cut.style).update(JSON.stringify(cut.look ?? {})).update(String(cut.faceCam)).update(JSON.stringify(seg));
  visualKey(seg, h);
  const prev = plan.segments[i - 1];
  if (prev && seg.transitionIn !== "cut") {
    h.update(JSON.stringify(prev));
    visualKey(prev, h);
  }
  return h.digest("hex").slice(0, 12);
};

// 5. The public folder holds only the media this plan uses, hard-linked where possible so large footage isn't copied.
const work = path.join(tmpdir(), `cut-${id}-${Date.now()}`);
const pub = `${work}-public`;
mkdirSync(path.join(pub, "media"), { recursive: true });
const place = (from: string, to: string) => {
  mkdirSync(path.dirname(to), { recursive: true });
  try {
    linkSync(from, to);
  } catch {
    copyFileSync(from, to);
  }
};
for (const m of new Set(plan.segments.flatMap((s) => s.media.flatMap((x) => (x.src ? [x.src.startsWith("media/") ? x.src : `media/${x.src}`] : []))))) {
  const from = path.join(videoDir, m);
  if (!existsSync(from)) throw new Error(`Media ${m} is missing from the video's folder.`);
  place(from, path.join(pub, m));
}
if (cut.faceCam) place(facecam, path.join(pub, "facecam.mp4"));

const t0 = Date.now();
const clipsDir = path.join(videoDir, "renders/cut", quality);
mkdirSync(clipsDir, { recursive: true });
const sheetsDir = path.join(editDir, "stills/cut");
mkdirSync(sheetsDir, { recursive: true });
const scratch = path.join(videoDir, "renders/.cut");
mkdirSync(scratch, { recursive: true });
let bundled = false;
try {
  const clips: string[] = [];
  let rendered = 0;
  for (const [i, seg] of plan.segments.entries()) {
    const clip = path.join(clipsDir, `${seg.id}-${keyOf(i)}.mp4`);
    if (!existsSync(clip) || forced.has(seg.id)) {
      if (!bundled) {
        remotion(["bundle", path.join(editDir, ".cut-entry.tsx"), "--out-dir", work, "--public-dir", pub, "--log", "error"]);
        bundled = true;
      }
      const started = Date.now();
      remotion(["render", work, "cut", clip, `--frames=${seg.from}-${seg.to - 1}`, "--muted", "--concurrency", concurrency, "--log", "error", ...(quality === "final" ? [] : ["--scale", "0.5"])]);
      for (const old of readdirSync(clipsDir)) if (old.startsWith(`${seg.id}-`) && old !== path.basename(clip)) rmSync(path.join(clipsDir, old));
      console.log(`rendered ${seg.id.padEnd(12)} ${String(seg.to - seg.from).padStart(5)} frames in ${((Date.now() - started) / 1000).toFixed(0)} s`);
      rendered++;
    } else console.log(`cached   ${seg.id}`);
    clips.push(clip);
    // Four moments of the segment in one image, so a plan can be checked by eye without watching the video.
    const sheet = path.join(sheetsDir, `${seg.id}.jpg`);
    if (!existsSync(sheet) || statSync(sheet).mtimeMs < statSync(clip).mtimeMs) {
      const n = seg.to - seg.from;
      const picks = [0.2, 0.45, 0.7, 0.95].map((f) => `eq(n\\,${Math.min(n - 1, Math.round(n * f))})`).join("+");
      run("ffmpeg", ["-v", "error", "-y", "-i", clip, "-vf", `select='${picks}',scale=640:-2,tile=2x2:padding=4:color=red`, "-fps_mode", "vfr", "-frames:v", "1", "-update", "1", sheet], root);
    }
  }
  for (const name of readdirSync(sheetsDir)) if (!plan.segments.some((seg) => `${seg.id}.jpg` === name)) rmSync(path.join(sheetsDir, name));

  // Every clip comes from the same composition and settings, so they join without re-encoding.
  const list = path.join(scratch, "clips.txt");
  writeFileSync(list, clips.map((c) => `file '${c}'`).join("\n"));
  const silent = path.join(scratch, "video.mp4");
  run("ffmpeg", ["-v", "error", "-y", "-f", "concat", "-safe", "0", "-i", list, "-c", "copy", silent], root);
  const out = path.join(videoDir, "renders", `cut-${quality}.mp4`);
  const dur = (plan.frames / FPS).toFixed(3);
  let sound = narrationWav;
  let gain = 0;
  if (cut.audio === "music") {
    sound = path.join(scratch, "bed.wav");
    renderBed(cut.music!.trackId, plan.frames / FPS, cut.mix ?? { musicDb: 0, musicStart: 0, fadeIn: 0.4, fadeOut: 3 }, sound);
    gain = gainToLufs(sound) + (cut.mix?.musicDb ?? 0);
  }
  run("ffmpeg", ["-v", "error", "-y", "-i", silent, "-i", sound, "-filter_complex", `[1:a]atrim=0:${dur},asetpts=N/SR/TB,volume=${gain.toFixed(2)}dB,alimiter=limit=0.89:level=false[a]`, "-map", "0:v", "-map", "[a]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-t", dur, out], root);
  console.log(`${path.relative(root, out)}: ${plan.segments.length} segments, ${rendered} rendered, ${plan.segments.length - rendered} cached, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  try {
    console.log(run("node", [path.join(root, "scripts/motion-qa.mjs"), out], root).trim());
  } catch (error) {
    console.log(String((error as { stdout?: Buffer }).stdout ?? "").trim());
    process.exitCode = 1;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
  rmSync(pub, { recursive: true, force: true });
  rmSync(scratch, { recursive: true, force: true });
}
