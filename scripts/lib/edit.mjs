// Shared helpers for the edit-stage scripts: locate a video's edit, write its Remotion entry and tsconfig, typecheck its scenes, and bundle it.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";

export const root = resolve(new URL("../..", import.meta.url).pathname);
export const pkg = join(root, "packages/video");

export const run = (cmd, argv, cwd = pkg) => execFileSync(cmd, argv, { cwd, stdio: ["ignore", "pipe", "inherit"] }).toString();
// Remotion's own binary rather than npx: npx under pnpm prints "Unknown env config" warnings into the render log.
export const remotion = (argv) => run(join(pkg, "node_modules/.bin/remotion"), argv);

// Same switch as the server (apps/server/src/studio/videos.ts), so test servers never touch the real videos/.
export const videosRoot = process.env.STUDIO_VIDEOS_DIR ? resolve(process.env.STUDIO_VIDEOS_DIR) : join(root, "videos");

export function prepareEdit(id) {
  const videoDir = join(videosRoot, id);
  const editDir = join(videoDir, "edit");
  if (!existsSync(join(editDir, "edit.json"))) throw new Error(`No edit/edit.json for ${id} yet (the edit plan writes it).`);
  const spec = JSON.parse(readFileSync(join(editDir, "edit.json"), "utf8"));
  const up = relative(editDir, pkg);

  // Per-video TypeScript config, so scenes that import @library typecheck like library code. @types first so react resolves with its types.
  const tsconfig = join(editDir, "tsconfig.json");
  if (!existsSync(tsconfig)) {
    writeFileSync(
      tsconfig,
      JSON.stringify(
        { extends: `${up}/tsconfig.json`, compilerOptions: { paths: { "@library/*": [`./${up}/src/library/*`], "*": [`./${up}/node_modules/@types/*`, `./${up}/node_modules/*`] } }, include: ["scenes"] },
        null,
        2,
      ),
    );
  }

  // The generated entry: every scene in edit.json registered as its own beat composition.
  const entry = join(editDir, ".entry.tsx");
  // Beats without a scene file yet render as a labelled placeholder (LongRoot), so a half-built edit still assembles.
  const scenes = spec.beats.map((b, i) => ({ ...b, name: `Scene${i}` })).filter((b) => existsSync(join(editDir, b.scene)));
  writeFileSync(
    entry,
    `// Generated by scripts/lib/edit.mjs from edit.json; do not edit.
import { registerRoot } from "remotion";
import { LongRoot } from "${relative(editDir, join(pkg, "src/long/compose")).split("\\").join("/")}";
import spec from "./edit.json";
${scenes.map((s) => `import ${s.name} from "./${s.scene.replace(/\.tsx?$/, "")}";`).join("\n")}
registerRoot(() => <LongRoot spec={spec as never} scenes={{ ${scenes.map((s) => `"${s.id}": ${s.name}`).join(", ")} }} />);
`,
  );
  return { id, videoDir, editDir, spec, entry };
}

// Typecheck the video's scenes; returns the compiler's error lines (empty when clean).
export function typecheckScenes(prep) {
  try {
    execFileSync(join(pkg, "node_modules/.bin/tsc"), ["-p", join(prep.editDir, "tsconfig.json"), "--noEmit", "--noUnusedLocals"], { cwd: prep.editDir, stdio: "pipe" });
    return [];
  } catch (e) {
    return String(e.stdout ?? e.message).split("\n").filter((l) => l.includes("error"));
  }
}

// Bundle once per run; footage in media/ becomes the public dir so scenes can use staticFile("media/…").
export function bundleEdit(prep) {
  const base = join(tmpdir(), `edit-${prep.id}-${Date.now()}`);
  const pub = `${base}-public`;
  mkdirSync(pub, { recursive: true });
  if (existsSync(join(prep.videoDir, "media"))) execFileSync("cp", ["-R", join(prep.videoDir, "media"), join(pub, "media")]);
  remotion(["bundle", prep.entry, "--out-dir", base, "--public-dir", pub, "--log", "error"]);
  return { dir: base, cleanup: () => (rmSync(base, { recursive: true, force: true }), rmSync(pub, { recursive: true, force: true })) };
}
