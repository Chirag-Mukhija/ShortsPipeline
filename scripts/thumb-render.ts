// Renders a video's code-drawn thumbnail: package/thumbnail.tsx (this video's own design, default-exporting a component that takes { hasFace }) becomes package/thumbnail.png at 1280×720, plus package/thumbnail-feed.png at phone-feed size for checking it reads small. The creator's cut-out photo is used when package/face.png exists.
// Usage: pnpm thumb:render <videoId>
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const root = path.resolve(new URL("..", import.meta.url).pathname);
const pkg = path.join(root, "packages/video");
const videosRoot = process.env.STUDIO_VIDEOS_DIR ? path.resolve(process.env.STUDIO_VIDEOS_DIR) : path.join(root, "videos");
const id = process.argv[2];
if (!id) {
  console.error("Usage: pnpm thumb:render <videoId>");
  process.exit(2);
}
const dir = path.join(videosRoot, id, "package");
const design = path.join(dir, "thumbnail.tsx");
if (!existsSync(design)) throw new Error(`No package/thumbnail.tsx for ${id} yet.`);
const face = path.join(dir, "face.png");
const hasFace = existsSync(face);
const rel = path.relative(dir, path.join(pkg, "src/thumb")).split(path.sep).join("/");
const entry = path.join(dir, ".thumb-entry.tsx");
writeFileSync(
  entry,
  `// Generated by scripts/thumb-render.ts; do not edit.
import { Composition, registerRoot } from "remotion";
import { THUMB_H, THUMB_W } from "${rel}";
import Thumbnail from "./thumbnail";
const Thumb = () => <Thumbnail hasFace={${hasFace}} />;
registerRoot(() => <Composition id="thumb" component={Thumb} durationInFrames={1} fps={30} width={THUMB_W} height={THUMB_H} />);
`,
);
const work = path.join(tmpdir(), `thumb-${id}-${Date.now()}`);
const pub = `${work}-public`;
mkdirSync(pub, { recursive: true });
if (hasFace) copyFileSync(face, path.join(pub, "face.png"));
const remotion = (argv: string[]) => execFileSync(path.join(pkg, "node_modules/.bin/remotion"), argv, { cwd: pkg, stdio: ["ignore", "pipe", "inherit"] });
const out = path.join(dir, "thumbnail.png");
try {
  remotion(["bundle", entry, "--out-dir", work, "--public-dir", pub, "--log", "error"]);
  remotion(["still", work, "thumb", out, "--log", "error"]);
} finally {
  rmSync(work, { recursive: true, force: true });
  rmSync(pub, { recursive: true, force: true });
  rmSync(entry, { force: true });
}
// The mobile home feed shows thumbnails about 360 px wide: if the text can't be read here, it can't be read at all.
execFileSync("ffmpeg", ["-v", "error", "-y", "-i", out, "-vf", "scale=360:-2", path.join(dir, "thumbnail-feed.png")]);
console.log(`package/thumbnail.png (${(statSync(out).size / 1024).toFixed(0)} KB, ${hasFace ? "with" : "without"} face) and package/thumbnail-feed.png`);
if (!hasFace) console.log("No package/face.png yet: the face slot is empty. Add the creator's cut-out photo and run this again.");
