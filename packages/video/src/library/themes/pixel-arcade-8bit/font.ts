// Bold fakes a heavier arcade face by smearing every pixel one to the right, so a glyph is 6 wide.
export const glyphW = (bold: boolean) => (bold ? 6 : 5);
export const GAP = 1;
export const bitWidth = (text: string, bold = true) => (text.length ? text.length * (glyphW(bold) + GAP) - GAP : 0);

export type Run = { x: number; y: number; w: number };

// Horizontal runs of one glyph, in glyph pixels, so a title is a few hundred rects rather than thousands.
const cache = new Map<string, Run[]>();
export const glyphRuns = (ch: string, bold: boolean): Run[] => {
  const key = `${ch}${bold ? "b" : ""}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const rows = GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"]!;
  const runs: Run[] = [];
  rows.forEach((r, y) => {
    const on = [...r].map((c) => c === "#");
    const filled = on.map((v, i) => v || (bold && i > 0 && on[i - 1]!));
    if (bold && on[4]) filled.push(true);
    let start = -1;
    for (let i = 0; i <= filled.length; i++) {
      if (filled[i] && start < 0) start = i;
      if (!filled[i] && start >= 0) {
        runs.push({ x: start, y, w: i - start });
        start = -1;
      }
    }
  });
  cache.set(key, runs);
  return runs;
};
